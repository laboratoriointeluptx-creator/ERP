app.use(`${env.API_PREFIX}/payments`, paymentRouter);
app.use(`${env.API_PREFIX}/supplier-invoices`, supplierInvoiceRouter);
app.use(`${env.API_PREFIX}/supplier-payments`, supplierPaymentRouter);
app.use(`${env.API_PREFIX}/dashboard`, dashboardRouter);
app.use(`${env.API_PREFIX}/settings`, settingRouter);
app.use(`${env.API_PREFIX}/taxes`, taxRouter);
app.use(`${env.API_PREFIX}/chart-of-accounts`, accountRouter);
app.use(`${env.API_PREFIX}/journal-entries`, accountingJournalEntryRouter);
app.use(`${env.API_PREFIX}/accounts-receivable`, accountsReceivableRouter);
