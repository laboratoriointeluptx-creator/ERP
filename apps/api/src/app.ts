import { requestIdMiddleware } from './shared/request-id.js';

export const app = express();

app.disable('x-powered-by');
app.use(requestIdMiddleware);
app.use(helmet());
const allowedOrigins = new Set(env.CORS_ORIGINS.split(',').map((origin) => origin.trim()).filter(Boolean));
app.use(cors({
  origin: (origin, callback) => {
    callback(null, !origin || allowedOrigins.has(origin));
  },
}));
app.use(express.json({ limit: '1mb' }));

app.use('/health', healthRouter(databaseHealth));
app.use(`${env.API_PREFIX}/health`, healthRouter(databaseHealth));
app.use(`${env.API_PREFIX}/auth`, authenticationRouter);
app.use(`${env.API_PREFIX}/organizations`, organizationRouter);
app.use(`${env.API_PREFIX}/users`, userRouter);
app.use(`${env.API_PREFIX}/customers`, customerRouter);
